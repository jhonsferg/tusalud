CREATE TABLE camas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo character varying(20) NOT NULL,
    area character varying(15) NOT NULL,
    piso integer,
    descripcion character varying(200),
    estado character varying(15) NOT NULL,
    precio_dia numeric(10,2) NOT NULL,
    activa boolean NOT NULL,
    CONSTRAINT uk_camas_codigo UNIQUE (codigo),
    CONSTRAINT camas_area_check CHECK (area IN ('HOSPITALIZACION', 'EMERGENCIA', 'UCI', 'OBSERVACION')),
    CONSTRAINT camas_estado_check CHECK (estado IN ('LIBRE', 'OCUPADA', 'MANTENIMIENTO', 'LIMPIEZA'))
);

CREATE INDEX idx_camas_area_estado ON camas (area, estado);

CREATE TABLE ingresos_hospitalarios (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo character varying(20) NOT NULL,
    tipo character varying(15) NOT NULL,
    estado character varying(15) NOT NULL,
    paciente_id bigint NOT NULL,
    cama_id bigint,
    medico_id bigint,
    motivo character varying(300) NOT NULL,
    diagnostico_ingreso character varying(300),
    fecha_ingreso timestamp(6) without time zone NOT NULL,
    fecha_alta timestamp(6) without time zone,
    diagnostico_alta character varying(300),
    indicaciones_alta character varying(500),
    cargo_acumulado numeric(12,2) NOT NULL,
    desde_en_cama timestamp(6) without time zone,
    triaje_nivel integer,
    triaje_presion_arterial character varying(20),
    triaje_frecuencia_cardiaca integer,
    triaje_frecuencia_respiratoria integer,
    triaje_temperatura numeric(4,1),
    triaje_saturacion_o2 integer,
    triaje_glasgow integer,
    triaje_motivo_consulta character varying(300),
    triaje_registrado_por_id bigint,
    triaje_fecha timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT uk_ingresos_hosp_codigo UNIQUE (codigo),
    CONSTRAINT fk_ingresos_hosp_paciente FOREIGN KEY (paciente_id) REFERENCES pacientes (id),
    CONSTRAINT fk_ingresos_hosp_cama FOREIGN KEY (cama_id) REFERENCES camas (id),
    CONSTRAINT fk_ingresos_hosp_medico FOREIGN KEY (medico_id) REFERENCES medicos (id),
    CONSTRAINT fk_ingresos_hosp_triaje_usuario FOREIGN KEY (triaje_registrado_por_id) REFERENCES usuarios (id),
    CONSTRAINT ingresos_hospitalarios_tipo_check CHECK (tipo IN ('PROGRAMADO', 'EMERGENCIA')),
    CONSTRAINT ingresos_hospitalarios_estado_check CHECK (estado IN ('ACTIVO', 'ALTA', 'CANCELADO')),
    CONSTRAINT ingresos_hospitalarios_triaje_check CHECK (triaje_nivel IS NULL OR triaje_nivel BETWEEN 1 AND 5)
);

CREATE INDEX idx_ingresos_hosp_estado_fecha ON ingresos_hospitalarios (estado, fecha_ingreso);
CREATE INDEX idx_ingresos_hosp_paciente ON ingresos_hospitalarios (paciente_id);
CREATE INDEX idx_ingresos_hosp_cama ON ingresos_hospitalarios (cama_id);

CREATE TABLE evoluciones_hospitalarias (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingreso_id bigint NOT NULL,
    tipo character varying(15) NOT NULL,
    nota character varying(1000) NOT NULL,
    presion_arterial character varying(20),
    frecuencia_cardiaca integer,
    temperatura numeric(4,1),
    saturacion_o2 integer,
    autor_id bigint NOT NULL,
    fecha timestamp(6) without time zone NOT NULL,
    CONSTRAINT fk_evoluciones_hosp_ingreso FOREIGN KEY (ingreso_id) REFERENCES ingresos_hospitalarios (id),
    CONSTRAINT fk_evoluciones_hosp_autor FOREIGN KEY (autor_id) REFERENCES usuarios (id),
    CONSTRAINT evoluciones_hospitalarias_tipo_check CHECK (tipo IN ('MEDICA', 'ENFERMERIA'))
);

CREATE INDEX idx_evoluciones_hosp_ingreso ON evoluciones_hospitalarias (ingreso_id, fecha);
