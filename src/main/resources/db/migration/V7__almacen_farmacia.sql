CREATE TABLE dispensaciones (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha timestamp(6) without time zone NOT NULL,
    comprobante character varying(20) NOT NULL,
    estado character varying(10) NOT NULL,
    paciente_id bigint,
    atencion_id bigint,
    usuario_id bigint NOT NULL,
    metodo_pago character varying(10) NOT NULL,
    total numeric(12, 2) NOT NULL,
    observaciones character varying(300),
    CONSTRAINT uk_dispensaciones_comprobante UNIQUE (comprobante),
    CONSTRAINT fk_dispensaciones_paciente FOREIGN KEY (paciente_id) REFERENCES pacientes (id),
    CONSTRAINT fk_dispensaciones_atencion FOREIGN KEY (atencion_id) REFERENCES atenciones (id),
    CONSTRAINT fk_dispensaciones_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT dispensaciones_estado_check CHECK (estado IN ('EMITIDA', 'ANULADA')),
    CONSTRAINT dispensaciones_metodo_check CHECK (metodo_pago IN ('EFECTIVO', 'TARJETA', 'YAPE', 'PLIN'))
);

CREATE INDEX idx_dispensaciones_fecha ON dispensaciones (fecha);
CREATE INDEX idx_dispensaciones_paciente ON dispensaciones (paciente_id);

CREATE TABLE dispensacion_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispensacion_id bigint NOT NULL,
    producto_id bigint NOT NULL,
    cantidad integer NOT NULL,
    precio_unitario numeric(10, 2) NOT NULL,
    subtotal numeric(12, 2) NOT NULL,
    receta_posicion integer,
    CONSTRAINT fk_dispensacion_items_dispensacion FOREIGN KEY (dispensacion_id) REFERENCES dispensaciones (id),
    CONSTRAINT fk_dispensacion_items_producto FOREIGN KEY (producto_id) REFERENCES productos (id),
    CONSTRAINT dispensacion_items_cantidad_check CHECK (cantidad > 0)
);
