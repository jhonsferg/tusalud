CREATE TABLE proveedores (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruc character varying(11) NOT NULL,
    razon_social character varying(150) NOT NULL,
    contacto character varying(100),
    telefono character varying(20),
    email character varying(120),
    direccion character varying(200),
    activo boolean NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT uk_proveedores_ruc UNIQUE (ruc)
);

CREATE TABLE productos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo character varying(30) NOT NULL,
    nombre character varying(150) NOT NULL,
    descripcion character varying(500),
    tipo character varying(15) NOT NULL,
    principio_activo character varying(150),
    presentacion character varying(100),
    unidad character varying(30) NOT NULL,
    precio_venta numeric(10, 2) NOT NULL,
    stock_minimo integer NOT NULL,
    requiere_receta boolean NOT NULL,
    activo boolean NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT uk_productos_codigo UNIQUE (codigo),
    CONSTRAINT productos_tipo_check CHECK (tipo IN ('MEDICAMENTO', 'INSUMO', 'REACTIVO', 'MATERIAL')),
    CONSTRAINT productos_precio_check CHECK (precio_venta >= 0),
    CONSTRAINT productos_stock_minimo_check CHECK (stock_minimo >= 0)
);

CREATE INDEX idx_productos_nombre ON productos (nombre);

CREATE TABLE ingresos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha timestamp(6) without time zone NOT NULL,
    documento character varying(40),
    proveedor_id bigint,
    observaciones character varying(300),
    total numeric(12, 2) NOT NULL,
    usuario_id bigint NOT NULL,
    CONSTRAINT fk_ingresos_proveedor FOREIGN KEY (proveedor_id) REFERENCES proveedores (id),
    CONSTRAINT fk_ingresos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);

CREATE TABLE lotes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id bigint NOT NULL,
    ingreso_id bigint,
    proveedor_id bigint,
    numero_lote character varying(40) NOT NULL,
    fecha_vencimiento date NOT NULL,
    cantidad_inicial integer NOT NULL,
    cantidad_actual integer NOT NULL,
    costo_unitario numeric(10, 2) NOT NULL,
    ubicacion character varying(60),
    created_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT fk_lotes_producto FOREIGN KEY (producto_id) REFERENCES productos (id),
    CONSTRAINT fk_lotes_ingreso FOREIGN KEY (ingreso_id) REFERENCES ingresos (id),
    CONSTRAINT fk_lotes_proveedor FOREIGN KEY (proveedor_id) REFERENCES proveedores (id),
    CONSTRAINT uk_lotes_producto_numero UNIQUE (producto_id, numero_lote),
    CONSTRAINT lotes_cantidad_check CHECK (cantidad_actual >= 0 AND cantidad_inicial > 0)
);

CREATE INDEX idx_lotes_producto_vencimiento ON lotes (producto_id, fecha_vencimiento);

CREATE TABLE movimientos_inventario (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha timestamp(6) without time zone NOT NULL,
    tipo character varying(10) NOT NULL,
    motivo character varying(30) NOT NULL,
    producto_id bigint NOT NULL,
    lote_id bigint NOT NULL,
    cantidad integer NOT NULL,
    usuario_id bigint NOT NULL,
    referencia character varying(40),
    observaciones character varying(300),
    CONSTRAINT fk_movimientos_producto FOREIGN KEY (producto_id) REFERENCES productos (id),
    CONSTRAINT fk_movimientos_lote FOREIGN KEY (lote_id) REFERENCES lotes (id),
    CONSTRAINT fk_movimientos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT movimientos_tipo_check CHECK (tipo IN ('ENTRADA', 'SALIDA', 'AJUSTE')),
    CONSTRAINT movimientos_motivo_check CHECK (motivo IN (
        'COMPRA', 'CONSUMO_INTERNO', 'MERMA', 'VENCIMIENTO', 'AJUSTE_NEGATIVO', 'AJUSTE_POSITIVO',
        'DISPENSACION', 'ANULACION_DISPENSACION'))
);

CREATE INDEX idx_movimientos_producto_fecha ON movimientos_inventario (producto_id, fecha);
CREATE INDEX idx_movimientos_referencia ON movimientos_inventario (referencia);

