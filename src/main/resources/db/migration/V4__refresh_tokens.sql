CREATE TABLE refresh_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id bigint NOT NULL,
    sesion_id bigint NOT NULL,
    familia uuid NOT NULL,
    token_hash character varying(64) NOT NULL,
    expira_en timestamp(6) without time zone NOT NULL,
    usado boolean NOT NULL,
    revocado boolean NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT uk_refresh_tokens_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_tokens_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT fk_refresh_tokens_sesion FOREIGN KEY (sesion_id) REFERENCES sesiones_usuario (id)
);

CREATE INDEX idx_refresh_tokens_usuario ON refresh_tokens (usuario_id);
CREATE INDEX idx_refresh_tokens_sesion ON refresh_tokens (sesion_id);
CREATE INDEX idx_refresh_tokens_familia ON refresh_tokens (familia);

ALTER TABLE notificaciones DROP CONSTRAINT notificaciones_tipo_check;
ALTER TABLE notificaciones ADD CONSTRAINT notificaciones_tipo_check CHECK (tipo IN (
    'CITA_CREADA', 'CITA_CONFIRMADA', 'CITA_CANCELADA', 'CITA_ATENDIDA', 'CITA_REPROGRAMADA',
    'RECORDATORIO_CITA', 'INICIO_SESION', 'CONTRASENA_CAMBIADA', 'PAGO_REGISTRADO', 'PAGO_REEMBOLSADO',
    'MFA_ACTIVADO', 'MFA_DESACTIVADO', 'PACIENTE_COMPARTIDO', 'ROLES_ACTUALIZADOS', 'SESION_SOSPECHOSA',
    'SISTEMA'));
