CREATE TABLE turnos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero character varying(10) NOT NULL,
    secuencia integer NOT NULL,
    fecha date NOT NULL,
    prioridad character varying(12) NOT NULL,
    estado character varying(12) NOT NULL,
    motivo character varying(300),
    consultorio character varying(50),
    paciente_id bigint NOT NULL,
    cita_id bigint,
    medico_id bigint,
    creado_en timestamp(6) without time zone NOT NULL,
    llamado_en timestamp(6) without time zone,
    inicio_atencion_en timestamp(6) without time zone,
    fin_atencion_en timestamp(6) without time zone,
    CONSTRAINT uk_turnos_numero_fecha UNIQUE (fecha, numero),
    CONSTRAINT uk_turnos_cita UNIQUE (cita_id),
    CONSTRAINT fk_turnos_paciente FOREIGN KEY (paciente_id) REFERENCES pacientes (id),
    CONSTRAINT fk_turnos_cita FOREIGN KEY (cita_id) REFERENCES citas (id),
    CONSTRAINT fk_turnos_medico FOREIGN KEY (medico_id) REFERENCES medicos (id),
    CONSTRAINT turnos_prioridad_check CHECK (prioridad IN ('NORMAL', 'PREFERENTE', 'URGENTE')),
    CONSTRAINT turnos_estado_check CHECK (estado IN ('EN_ESPERA', 'LLAMADO', 'EN_ATENCION', 'ATENDIDO', 'AUSENTE', 'CANCELADO'))
);

CREATE INDEX idx_turnos_fecha_estado ON turnos (fecha, estado);

CREATE INDEX idx_turnos_medico_fecha ON turnos (medico_id, fecha);
