CREATE TABLE eventos_calendario (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id bigint NOT NULL,
    titulo character varying(120) NOT NULL,
    descripcion character varying(500),
    ubicacion character varying(120),
    tipo character varying(15) NOT NULL,
    inicio timestamp(6) without time zone NOT NULL,
    fin timestamp(6) without time zone NOT NULL,
    todo_el_dia boolean NOT NULL,
    color character varying(10),
    completado boolean NOT NULL,
    recordatorio_minutos integer,
    recordatorio_enviado boolean NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT fk_eventos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
    CONSTRAINT eventos_calendario_tipo_check CHECK (tipo IN ('TAREA', 'REUNION', 'RECORDATORIO', 'PERSONAL', 'BLOQUEO')),
    CONSTRAINT eventos_calendario_color_check CHECK (color IS NULL OR color IN ('AZUL', 'VERDE', 'ROJO', 'NARANJA', 'MORADO', 'GRIS'))
);

CREATE INDEX idx_eventos_usuario_inicio ON eventos_calendario (usuario_id, inicio);

ALTER TABLE notificaciones DROP CONSTRAINT notificaciones_tipo_check;
ALTER TABLE notificaciones ADD CONSTRAINT notificaciones_tipo_check CHECK (tipo IN (
    'CITA_CREADA', 'CITA_CONFIRMADA', 'CITA_CANCELADA', 'CITA_ATENDIDA', 'CITA_REPROGRAMADA',
    'RECORDATORIO_CITA', 'RECORDATORIO_EVENTO', 'INICIO_SESION', 'CONTRASENA_CAMBIADA', 'PAGO_REGISTRADO',
    'PAGO_REEMBOLSADO', 'MFA_ACTIVADO', 'MFA_DESACTIVADO', 'PACIENTE_COMPARTIDO', 'ROLES_ACTUALIZADOS',
    'SESION_SOSPECHOSA', 'SISTEMA'));
