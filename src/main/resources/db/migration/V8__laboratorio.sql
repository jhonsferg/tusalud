CREATE TABLE examenes_laboratorio (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo character varying(20) NOT NULL,
    nombre character varying(150) NOT NULL,
    categoria character varying(20) NOT NULL,
    muestra character varying(10) NOT NULL,
    precio numeric(10,2) NOT NULL,
    tiempo_entrega_horas integer NOT NULL,
    indicaciones character varying(300),
    activo boolean NOT NULL,
    CONSTRAINT uk_examenes_codigo UNIQUE (codigo),
    CONSTRAINT examenes_laboratorio_categoria_check CHECK (categoria IN ('HEMATOLOGIA', 'BIOQUIMICA', 'ORINA', 'INMUNOLOGIA', 'MICROBIOLOGIA', 'OTROS')),
    CONSTRAINT examenes_laboratorio_muestra_check CHECK (muestra IN ('SANGRE', 'ORINA', 'HECES', 'SALIVA', 'OTRA'))
);

CREATE TABLE parametros_examen (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    examen_id bigint NOT NULL,
    nombre character varying(100) NOT NULL,
    unidad character varying(20),
    tipo character varying(10) NOT NULL,
    valor_min numeric(12,3),
    valor_max numeric(12,3),
    orden integer NOT NULL,
    CONSTRAINT fk_parametros_examen FOREIGN KEY (examen_id) REFERENCES examenes_laboratorio (id),
    CONSTRAINT parametros_examen_tipo_check CHECK (tipo IN ('NUMERICO', 'TEXTO'))
);

CREATE INDEX idx_parametros_examen_examen ON parametros_examen (examen_id);

CREATE TABLE ordenes_laboratorio (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo character varying(20) NOT NULL,
    fecha timestamp(6) without time zone NOT NULL,
    estado character varying(15) NOT NULL,
    prioridad character varying(10) NOT NULL,
    paciente_id bigint NOT NULL,
    medico_id bigint NOT NULL,
    atencion_id bigint,
    indicaciones character varying(500),
    total numeric(10,2) NOT NULL,
    toma_muestra_en timestamp(6) without time zone,
    completada_en timestamp(6) without time zone,
    motivo_cancelacion character varying(300),
    created_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT uk_ordenes_lab_codigo UNIQUE (codigo),
    CONSTRAINT fk_ordenes_lab_paciente FOREIGN KEY (paciente_id) REFERENCES pacientes (id),
    CONSTRAINT fk_ordenes_lab_medico FOREIGN KEY (medico_id) REFERENCES medicos (id),
    CONSTRAINT fk_ordenes_lab_atencion FOREIGN KEY (atencion_id) REFERENCES atenciones (id),
    CONSTRAINT ordenes_laboratorio_estado_check CHECK (estado IN ('SOLICITADA', 'MUESTRA_TOMADA', 'EN_PROCESO', 'COMPLETADA', 'CANCELADA')),
    CONSTRAINT ordenes_laboratorio_prioridad_check CHECK (prioridad IN ('NORMAL', 'URGENTE'))
);

CREATE INDEX idx_ordenes_lab_estado_fecha ON ordenes_laboratorio (estado, fecha);
CREATE INDEX idx_ordenes_lab_paciente ON ordenes_laboratorio (paciente_id);
CREATE INDEX idx_ordenes_lab_medico ON ordenes_laboratorio (medico_id);

CREATE TABLE items_orden_lab (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id bigint NOT NULL,
    examen_id bigint NOT NULL,
    estado character varying(15) NOT NULL,
    observaciones character varying(500),
    fecha_resultado timestamp(6) without time zone,
    validado_por_id bigint,
    CONSTRAINT fk_items_orden_lab_orden FOREIGN KEY (orden_id) REFERENCES ordenes_laboratorio (id),
    CONSTRAINT fk_items_orden_lab_examen FOREIGN KEY (examen_id) REFERENCES examenes_laboratorio (id),
    CONSTRAINT fk_items_orden_lab_validador FOREIGN KEY (validado_por_id) REFERENCES usuarios (id),
    CONSTRAINT items_orden_lab_estado_check CHECK (estado IN ('PENDIENTE', 'CON_RESULTADO', 'VALIDADO'))
);

CREATE INDEX idx_items_orden_lab_orden ON items_orden_lab (orden_id);

CREATE TABLE resultados_lab (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id bigint NOT NULL,
    parametro_id bigint,
    parametro_nombre character varying(100) NOT NULL,
    unidad character varying(20),
    valor character varying(100) NOT NULL,
    valor_min numeric(12,3),
    valor_max numeric(12,3),
    fuera_de_rango boolean NOT NULL,
    CONSTRAINT fk_resultados_lab_item FOREIGN KEY (item_id) REFERENCES items_orden_lab (id)
);

CREATE INDEX idx_resultados_lab_item ON resultados_lab (item_id);
